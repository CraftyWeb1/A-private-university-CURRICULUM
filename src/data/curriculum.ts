export function seedSchools(): School[] {
  return JSON.parse(JSON.stringify(SCHOOLS)) as School[]
}

export function seedCourses(): Course[] {
  return JSON.parse(JSON.stringify(COURSES)) as Course[]
}

export function topicKey(courseId: string, topic: string) {
  const slug = topic
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 72)
  return `${courseId}:${slug}`
}

export function allTopics() {
  return COURSES.flatMap((course) =>
    course.topics.map((topic) => ({ course, topic, key: topicKey(course.id, topic) })),
  )
}
